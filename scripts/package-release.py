ROOT = Path(__file__).resolve().parents[1]
SOURCE_ITEMS = ('src','scripts','tests','dsh','cognitive','docs','web','vendor','launcher.py','Self_model.txt','SYS_Prompt.txt','start-web.bat','.gitignore','.gitattributes','README.md','LICENSE','THIRD_PARTY_NOTICES.md','CHANGELOG.md','package.json','package-lock.json','config.example.json','start.bat','start-dsh.bat','login.bat')
SECRET_NAMES = {'id_rsa','id_ed25519','id_ecdsa','id_dsa','.env','.credentials.yaml','weixin-credentials.json','dsh-connection.json','qq-connection.json','qq-gateway-credentials.json'}
JUNK = {'.git','.research','Release','Archive','__pycache__','coverage','.cache','.npm','cache','caches','logs-cache','session_projcache'}
SECRET_FIELDS = {'token','bot_token','access_token','refresh_token','context_token','get_updates_buf','cookie','authorization','password','passwordmd5','api_key','apikey','secret','client_secret','aes','aes_key','filekey','privatekey','private_key','signing_key'}
PAIR = re.compile(r'''((?:["']?(?:bot_token|access_token|refresh_token|context_token|cookie|authorization|password|api_key|apiKey|aes_key)["']?)\s*[:=]\s*)(?:"[^"\r\n]*"|'[^'\r\n]*'|[^\s,;}\]]+)''', re.I)
URL_AUTH = re.compile(r'([?&](?:token|access_token|rkey|authkey|signature|sig|key)=)[^&\s"\'<>]+', re.I)

def excluded(name):
    p = Path(name)
    parts = p.parts
    lower = [x.lower() for x in parts]
    if p.is_absolute() or '..' in parts or any(x in JUNK for x in parts): return True
    if any(x in SECRET_NAMES or x in ('credentials','secrets','private-keys','.ssh','.aws','.codex','.agents') for x in lower): return True
    if 'credential' in p.name.lower() and p.suffix.lower() in ('.json','.yaml','.yml','.ini','.dat'):return True
    if any(x.startswith('.env.') or x.endswith(('.key','.pem','.p12','.pfx','.jks','-wal','-shm','-journal','.pyc','.partial','.zip','.7z','.dsf','.tar','.gz')) for x in lower): return True
    if p.name.startswith('instance-lock') or p.name.endswith('.lock') or p.name=='autostart.flag': return True
    if name.startswith('data/qq-gateway/') or name.startswith('data/recovery-') or name.startswith('data/model-smoke/'): return True
    if name.startswith('.runtime/home/profiles/'): return True  # Regenerated by supported --from-default-profile.
    if name.startswith('.runtime/home/llm-deepseek/'): return True  # Remote upload cache, not source history.
    if name.startswith('.runtime/qq-gateway/') and (any(x in ('config','qqnt','user_data','userdata','nt_data') for x in lower) or p.suffix.lower() in ('.db','.sqlite')): return True
    if 'node_modules' in parts and (any(x in ('test','tests','fixtures','example','examples') for x in lower) or re.search(r'\.(?:test|spec)\.', p.name)): return True
    if name in ('.runtime/home/.anonymous-user-id','.runtime/weixin-resolved.patch.yml'): return True
    return False

def scrub_text(value):
    value = re.sub(r'\bsk-[A-Za-z0-9_-]{8,}', '[REMOVED_API_KEY]', value)
    value = re.sub(r'\b(?:Bearer|Basic)\s+[A-Za-z0-9_+/=.-]{8,}', '[REMOVED_AUTH]', value, flags=re.I)
    value = PAIR.sub(lambda m:m[1]+'"[REMOVED_CREDENTIAL]"', value)
    return URL_AUTH.sub(lambda m:m[1]+'REMOVED', value)

def scrub(value):
    if isinstance(value, dict):
        return {k:(None if k.lower() in SECRET_FIELDS and isinstance(v,str) else scrub(v)) for k,v in value.items()}
    if isinstance(value,list): return [scrub(v) for v in value]
    if isinstance(value,str): return scrub_text(value)
    return value

def scrub_value(text):
    try: return json.dumps(scrub(json.loads(text)),ensure_ascii=False,separators=(',',':'))
    except (ValueError,TypeError): return scrub_text(text)

def digest(file):
    h=hashlib.sha256()
    with file.open('rb') as f:
        for block in iter(lambda:f.read(1024*1024),b''):h.update(block)
    return h.hexdigest()

def copy_db(source,dest):
    src=sqlite3.connect(source.as_uri()+'?mode=ro',uri=True);out=sqlite3.connect(dest)
    counts={}
    try:
        src.backup(out)
        # Disable FK checks only in the disposable export. Counts of history tables stay intact.
        out.execute('PRAGMA foreign_keys=OFF')
        tables=[r[0] for r in out.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")]
        for table in tables:
            if table.startswith('raw_fts') or table.startswith('memory_fts'): continue
            q='"'+table.replace('"','""')+'"'
            columns=[r[1] for r in out.execute('PRAGMA table_info('+q+')')]
            if table=='uploads':out.execute('DELETE FROM '+q);continue
            if table=='meta' and {'key','value'}<=set(columns):out.execute("DELETE FROM meta WHERE key LIKE 'cursor:%' OR key LIKE 'typing:%'")
            # Generic text sanitization covers serialized payloads, event logs and notes, without output.
            for col in columns:
                qc='"'+col.replace('"','""')+'"'
                rows=out.execute('SELECT rowid,'+qc+' FROM '+q+' WHERE typeof('+qc+")='text'").fetchall()
                for rowid,value in rows:
                    clean=scrub_value(value)
                    if source.name=='bridge.sqlite' and table=='jobs' and col=='payload':
                        p=json.loads(clean)
                        if 'context' in p:p['context']=None
                        clean=json.dumps(p,ensure_ascii=False,separators=(',',':'))
                    if col.lower() in SECRET_FIELDS:clean=''
                    if clean!=value:out.execute('UPDATE '+q+' SET '+qc+'=? WHERE rowid=?',(clean,rowid))
            counts[table]=out.execute('SELECT count(*) FROM '+q).fetchone()[0]
        for index,table in (('raw_fts','raw_events'),('memory_fts','memories')):
            if index in tables and table in tables:
                out.execute('DELETE FROM '+index)
                out.execute('INSERT INTO '+index+'(id,scope,text) SELECT id,scope,text FROM '+table)
        if source.name=='interaction.sqlite' and 'settings' in tables:
            out.execute("INSERT OR REPLACE INTO settings VALUES('paused','true')")
            out.execute("INSERT OR REPLACE INTO settings VALUES('qq-groups','{\"allowed\":[]}')")
            out.execute("DELETE FROM settings WHERE k IN ('qq','qq-live')")
        out.commit()
        # Remove superseded secret bytes from SQLite free pages in the copy.
        out.execute('PRAGMA journal_mode=DELETE');out.execute('VACUUM')
        if out.execute('PRAGMA integrity_check').fetchone()[0]!='ok':raise ValueError('package-db-integrity')
    finally:out.close();src.close()
    return counts

def session_copy(source,dest,root):
    # Node 24 supplies the same public Zstandard codec used by the installed DSH.
    with tempfile.TemporaryDirectory(dir=dest.parent) as temp:
        plain=Path(temp)/'session.jsonl'
        run_codec(root,'decode',source,plain)
        records=[]
        with plain.open(encoding='utf-8') as f:
            for line in f:
                if line.strip():records.append(json.dumps(scrub(json.loads(line)),ensure_ascii=False,separators=(',',':')))
        plain.write_text('\n'.join(records)+'\n',encoding='utf-8')
        run_codec(root,'encode',plain,dest)
    return len(records)

def run_codec(root,mode,source,dest):
    result=subprocess.run(['node',str(root/'scripts/package-session-codec.js'),mode,str(source),str(dest)],capture_output=True,creationflags=subprocess.CREATE_NO_WINDOW if os.name=='nt' else 0)
    if result.returncode:raise ValueError('package-session-codec-failed')

def files_under(root,item):
    start=root/item
    if not start.exists() or start.is_symlink():return
    if start.is_file():
        if not excluded(item):yield start,item
        return
    for parent,dirs,files in os.walk(start,followlinks=False):
        dirs[:]=sorted(d for d in dirs if not (Path(parent)/d).is_symlink() and not excluded((Path(parent)/d).relative_to(root).as_posix()+'/'))
        for name in sorted(files):
            file=Path(parent)/name;relative=file.relative_to(root).as_posix()
            if not excluded(relative) and not file.is_symlink() and file.is_file():yield file,relative

def make_archive(stage,target,edition,stats):
    entries={}
    partial=target.with_suffix('.zip.partial')
    with zipfile.ZipFile(partial,'x',zipfile.ZIP_DEFLATED,compresslevel=5) as z:
        for file in sorted(stage.rglob('*')):
            if not file.is_file():continue
            name=file.relative_to(stage).as_posix()
            entries[name]={'bytes':file.stat().st_size,'sha256':digest(file)}
            z.write(file,name)
        manifest={'format':'DeepSeek:Friend Exchange','version':1,'edition':edition,'appVersion':stats['appVersion'],'createdAt':datetime.now(timezone.utc).isoformat(),'credentialsIncluded':False,'historyPreserved':edition=='friend','files':entries,'stateCounts':stats.get('stateCounts',{}),'originalRoot':stats.get('originalRoot')}
        z.writestr('PACKAGE_MANIFEST.json',json.dumps(manifest,ensure_ascii=False,indent=2))
    verify(partial)
    if target.exists():raise ValueError('package-output-already-exists')
    os.replace(partial,target)
    return {'file':target.name,'bytes':target.stat().st_size,'sha256':digest(target),'files':len(entries)}

def verify(target):
    with zipfile.ZipFile(target) as z:
        infos=z.infolist();manifest=json.loads(z.read('PACKAGE_MANIFEST.json'))
        if len({i.filename.casefold() for i in infos})!=len(infos):raise ValueError('package-duplicate-path')
        if set(z.namelist())!={'PACKAGE_MANIFEST.json',*manifest['files']}:raise ValueError('package-inventory')
        for name,meta in manifest['files'].items():
            if excluded(name):raise ValueError('package-forbidden-path')
            with z.open(name) as f:
                h=hashlib.sha256();size=0
                for block in iter(lambda:f.read(1024*1024),b''):h.update(block);size+=len(block)
            if h.hexdigest()!=meta['sha256'] or size!=meta['bytes']:raise ValueError('package-checksum')
        return {'edition':manifest['edition'],'appVersion':manifest['appVersion'],'files':len(manifest['files']),'stateCounts':manifest.get('stateCounts',{})}

def build(root=ROOT,edition='all'):
    root=Path(root).resolve();version=json.loads((root/'package.json').read_text(encoding='utf-8'))['version']
    release=root/'Release'/('v'+version)
    if not release.exists():raise ValueError('package-run-npm-release-first')
    if any(p.is_symlink() for p in [release,release.parent]):raise ValueError('package-symlink-output')
    editions=['source','friend'] if edition=='all' else [edition]
    targets={e:release/f'deepseek-friend-v{version}-{e}.zip' for e in editions}
    if any(f.exists() for f in targets.values()):raise ValueError('package-output-already-exists')
    if 'friend' in editions:
        from dsf import offline,settings
        data,port=settings(root)
        if data!=root/'data':raise ValueError('package-custom-data-location-not-supported')
        guard=offline(root,data,port)
    else:
        from contextlib import nullcontext
        guard=nullcontext()
    reports=[]
    with tempfile.TemporaryDirectory(prefix='.exchange-',dir=release) as temp:
        stage=Path(temp)
        if os.name=='nt':
            result=subprocess.run(['node','--input-type=module','-e',"import {secureDirectory} from './src/security.js';secureDirectory(process.argv[1]);",str(stage)],cwd=root,capture_output=True,creationflags=subprocess.CREATE_NO_WINDOW)
            if result.returncode:raise ValueError('package-output-acl')
        else:stage.chmod(0o700)
        with guard:
            for e in editions:
                folder=stage/e;folder.mkdir();stats={'appVersion':version,'originalRoot':str(root) if e=='friend' else None,'stateCounts':{}}
                copied=0
                items=list(SOURCE_ITEMS)
                if e=='friend':items+=['config.json','data','node_modules','.runtime']
                # Dependencies/binaries are copied; known account/config/cache paths are never opened.
                for item in items:
                    for source,name in files_under(root,item):
                        dest=folder/name;dest.parent.mkdir(parents=True,exist_ok=True)
                        if e=='friend' and source.suffix in ('.sqlite','.db'):
                            stats['stateCounts'][name]=copy_db(source,dest)
                        elif e=='friend' and name.startswith('.runtime/home/sessions/') and name.endswith('.jsonl.zstd'):
                            stats['stateCounts'][name]={'records':session_copy(source,dest,root)}
                        elif e=='friend' and (name.startswith(('data/','.runtime/home/','.runtime/qq-gateway/')) and 'node_modules' not in Path(name).parts or name=='config.json') and source.suffix.lower() in ('.json','.jsonl','.txt','.md','.log','.yaml','.yml'):
                            text=source.read_bytes().decode('utf-8')
                            if source.suffix=='.json':
                                value=scrub(json.loads(text))
                                if name=='config.json':
                                    (folder/'config.original-sanitized.json').write_text(json.dumps(value,ensure_ascii=False,indent=2),encoding='utf-8')
                                    value['dataDir']='data';value.setdefault('dsh',{})['cwd']='data/workspaces'
                                    value.setdefault('weixin',{})['enabled']=False;value.setdefault('qq',{})['enabled']=False
                                    value.setdefault('cognitive',{})['enabled']=False
                                    value['cognitive'].setdefault('dreaming',{})['enabled']=False
                                if name=='config.json' or value!=json.loads(text):text=json.dumps(value,ensure_ascii=False,indent=2)
                            else:text=scrub_text(text)
                            dest.write_bytes(text.encode('utf-8'))
                        else:shutil.copyfile(source,dest)
                        copied+=1
                        if copied%2000==0:print(json.dumps({'event':'package-copy','edition':e,'files':copied}),flush=True)
                (folder/'PACKAGE_README.md').write_text((root/'docs'/('friend-package.md' if e=='friend' else 'source-package.md')).read_text(encoding='utf-8'),encoding='utf-8')
                (folder/'PACKAGE_STATE.json').write_text(json.dumps(stats,ensure_ascii=False,indent=2),encoding='utf-8')
        # Services may restart once staging is complete; compression and hash checks only use copies.
        (release/'PACKAGING_STAGED').write_text('snapshot complete',encoding='ascii')
        print(json.dumps({'event':'package-staged','servicesMayRestart':True}),flush=True)
        for e in editions:
            stats=json.loads((stage/e/'PACKAGE_STATE.json').read_text(encoding='utf-8'))
            private_target=stage/targets[e].name
            reports.append(make_archive(stage/e,private_target,e,stats))
            if targets[e].exists():raise ValueError('package-output-already-exists')
            os.replace(private_target,targets[e])  # Same volume: retain the private file ACL.
    (release/'PACKAGES.json').write_text(json.dumps(reports,indent=2),encoding='utf-8')
    (release/'CHECKSUMS.sha256').write_text(''.join(r['sha256']+'  '+r['file']+'\n' for r in reports),encoding='ascii')
    return reports

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--edition',choices=['source','friend','all'],default='all');parser.add_argument('--verify',type=Path);args=parser.parse_args()
    try:print(json.dumps(verify(args.verify) if args.verify else build(edition=args.edition),ensure_ascii=False))
    except Exception as e:
        # Do not print exception strings: parsers may include source content or credentials.
        code=str(e) if isinstance(e,ValueError) and re.fullmatch(r'package-[a-z-]+',str(e)) else None
        print(json.dumps({'error':code or 'package-failed','kind':type(e).__name__}));raise SystemExit(1)
